// Downloads the Calligraphy Studio fonts (TTF) and their licence files from Google Fonts,
// and writes fonts/calligraphy/fonts.css. Run once: node tools/fetch-calligraphy-fonts.mjs
// Every font here is checked to be under the SIL Open Font License; the script stops if not.
import fs from 'node:fs';
import path from 'node:path';
const OUT = path.resolve('fonts/calligraphy');
const FAMILIES = [
  ['Pinyon Script'], ['Italianno'], ['Monsieur La Doulaise'], ['Mrs Saint Delafield'], ['Petit Formal Script'], ['Alex Brush'],
  ['UnifrakturCook', '700'], ['UnifrakturMaguntia'], ['Grenze Gotisch', '500;700'], ['Great Vibes'], ['Tangerine', '400;700'], ['Parisienne'],
  ['Dancing Script', '400;700'], ['Sacramento'], ['Herr Von Muellerhoff'], ['Ms Madi'], ['WindSong', '400;500'], ['Allura'],
  ['Corinthia', '400;700'], ['Rouge Script'], ['Ballet'], ['Imperial Script'], ['Mea Culpa'], ['Water Brush'],
  ['Cormorant Garamond', '400;500;600'], ['Cormorant Garamond', 'ital400'], ['Cormorant SC', '500;600'],
  ['Amita', '400;700'], ['Kalam', '400;700'], ['Tiro Devanagari Hindi'], ['Rozha One'],
  ['Tiro Gurmukhi'], ['Baloo Paaji 2', '500;700'], ['Noto Serif Gurmukhi', '400;600'],
];
const slug = (n) => n.toLowerCase().replace(/[^a-z0-9]+/g, '');
const get = async (u) => { const r = await fetch(u); if (!r.ok) throw new Error(u + ' ' + r.status); return r; };
let css = '/* Calligraphy Studio fonts, self-hosted so exports can embed them. Generated by tools/fetch-calligraphy-fonts.mjs */\n';
const lic = [];
for (const [name, w] of FAMILIES) {
  const fam = name.replace(/ /g, '+');
  const q = !w ? fam : w.startsWith('ital') ? `${fam}:ital,wght@1,${w.slice(4)}` : `${fam}:wght@${w}`;
  const text = await (await get(`https://fonts.googleapis.com/css2?family=${q}`)).text();
  for (const block of text.split('@font-face').slice(1)) {
    const style = /font-style:\s*(\w+)/.exec(block)[1], weight = /font-weight:\s*(\d+)/.exec(block)[1];
    const url = /url\((.*?)\)/.exec(block)[1];
    const file = `${slug(name)}-${weight}${style === 'italic' ? 'i' : ''}.ttf`;
    fs.writeFileSync(path.join(OUT, file), Buffer.from(await (await get(url)).arrayBuffer()));
    css += `@font-face{font-family:'${name}';font-style:${style};font-weight:${weight};font-display:swap;src:url('${file}') format('truetype')}\n`;
  }
  if (!lic.some((l) => l.name === name)) {
    const t = await (await get(`https://raw.githubusercontent.com/google/fonts/main/ofl/${slug(name)}/OFL.txt`)).text();
    if (!/SIL OPEN FONT LICENSE/i.test(t)) throw new Error('Not OFL: ' + name);
    fs.writeFileSync(path.join(OUT, `OFL-${slug(name)}.txt`), t);
    lic.push({ name, copyright: (t.split('\n').find((l) => /copyright/i.test(l)) || '').trim() });
  }
  console.log('ok', name);
}
fs.writeFileSync(path.join(OUT, 'fonts.css'), css);
fs.writeFileSync(path.join(OUT, 'LICENSES.md'), `# Calligraphy Studio fonts and licences\n\nEvery font in this folder is licensed under the **SIL Open Font License 1.1** (OFL). Its full licence text is in the matching \`OFL-<name>.txt\` file. The OFL allows using, embedding (including in exported PNG, JPG and PDF files) and redistributing these fonts with InviteX. It does not allow selling the font files on their own, or shipping a modified font under its reserved name. Source: [Google Fonts](https://github.com/google/fonts/tree/main/ofl).\n\n| Font | Copyright line from its licence | Licence |\n| --- | --- | --- |\n${lic.map((l) => `| ${l.name} | ${l.copyright.replace(/\|/g, '/')} | [OFL 1.1](OFL-${slug(l.name)}.txt) |`).join('\n')}\n`);
